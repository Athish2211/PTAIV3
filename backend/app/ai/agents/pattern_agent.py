"""
Pattern Agent for finding co-prescription associations.
"""
from typing import Dict, Any, List
from app.ai.llm.client import llm_client
import json

class PatternAgent:
    PROMPT = """
You are the Pattern Agent.
Review the following association rules (co-prescriptions) generated by our FP-Growth algorithm.
Summarize the strongest patterns, explaining the Support, Confidence, and Lift metrics in simple terms for a clinical user.
Do not evaluate the clinical validity of the combinations, just explain the statistical association found in the dataset.

Association Rules:
{data}

Provide your response in clear markdown format.
"""

    async def analyze(self, query: str, rules_data: List[Dict[str, Any]]) -> str:
        """Analyze association rules and explain patterns."""
        context_str = json.dumps(rules_data, indent=2)
        formatted_prompt = self.PROMPT.format(data=context_str)
        
        response = await llm_client.generate(
            prompt=query,
            system=formatted_prompt,
            temperature=0.2
        )
        return response

pattern_agent = PatternAgent()
